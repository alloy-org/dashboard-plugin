// Read and progressively write the per-quarter note associating quarterly-plan projects with their existing
// tasks, generated task ideas, and completions. Each project owns one h2 section, so a background pass can
// advance a single project through a section-scoped write without rewriting the rest of the note.
import { DASHBOARD_NOTE_TAG } from "constants/settings";
import { guideHeadingRanges, guideSectionRange } from "plan-wizard/vision-guide-markdown";
import { checkedAppResult, MAXIMUM_GUIDE_SECTION_CHARACTERS, replaceGuideSection } from "plan-wizard/vision-guide-notes";
import { openIdeas } from "project-idea-records";
import { ACTIVE_PROJECTS_HEADING, initialProjectTaskStoreMarkdown, PAST_PROJECTS_HEADING,
  projectSectionHeadingText } from "project-task-store-markdown";
import QuarterProject from "quarter-project";
import { logIfEnabled } from "util/log";

// ----------------------------------------------------------------------------------------------
// @desc Render the collected task ideas for the agenda prompt, so a day that needs a suggestion for a due
//   project can draw on text generated by an earlier background pass instead of waiting for one now. Only the ideas
//   awaiting the user's decision are offered, and only projects that hold some are described, keeping the prompt free
//   of empty scaffolding.
// @param {Array<object>} storedRecords - Records from readCollectedProjectTasks.
// @returns {string} Markdown describing each project's pre-generated ideas, empty when none are stored.
export function collectedIdeasMarkdown(storedRecords) {
  const recordsWithOpenIdeas = (storedRecords || []).map(record => ({ record, ideas: openIdeas(record.suggestedTasks) }));
  const projectsWithIdeas = recordsWithOpenIdeas.filter(entry => entry.ideas.length);
  if (!projectsWithIdeas.length) return "";
  const projectLines = projectsWithIdeas.map(({ ideas, record }) => {
    const ideaLines = ideas.map(idea => `  - ${ idea.taskText }`).join("\n");
    return `- ${ record.summary } (project:${ record.uuid }):\n${ ideaLines }`;
  });
  return projectLines.join("\n");
}

// ----------------------------------------------------------------------------------------------
// @desc Open the store note for a quarter, creating it with both project roots when it does not yet exist.
//   The returned handle is a bare { uuid } literal because a handle produced by the bridge cannot be written
//   through; see lib/util/note-handles.js for why a write through such an object silently reports success.
// @param {object} app - Host-compatible Amplenote API.
// @param {object} scope - Resolved plan scope.
// @returns {Promise<object>} { content, noteHandle } for the existing or newly created note.
export async function openProjectTaskStore(app, scope) {
  const name = projectTaskStoreNoteName(scope);
  const found = checkedAppResult(await app.findNote({ name }));
  if (found?.uuid) {
    const content = checkedAppResult(await app.getNoteContent({ uuid: found.uuid }));
    if (typeof content !== "string") throw new Error(`Could not read project task store "${ name }"`);
    if (content.trim()) return { content, noteHandle: { uuid: found.uuid } };
    const seeded = initialProjectTaskStoreMarkdown();
    checkedAppResult(await app.replaceNoteContent({ uuid: found.uuid }, seeded));
    return { content: seeded, noteHandle: { uuid: found.uuid } };
  }
  const created = checkedAppResult(await app.createNote(name, [DASHBOARD_NOTE_TAG], { archive: true }));
  const uuid = typeof created === "string" ? created : created?.uuid;
  if (!uuid) throw new Error(`Could not create project task store "${ name }"`);
  const seeded = initialProjectTaskStoreMarkdown();
  checkedAppResult(await app.replaceNoteContent({ uuid }, seeded));
  return { content: seeded, noteHandle: { uuid } };
}

// ----------------------------------------------------------------------------------------------
// @desc Name the quarter-scoped store note, aligning with the quarterly plan note it draws its projects from.
// @param {object} scope - Resolved plan scope with `domainName`, `quarter`, and `year`.
// @returns {string} Note title.
export function projectTaskStoreNoteName(scope) {
  return `Project Tasks Q${ scope.quarter } ${ scope.year } ${ scope.domainName }`;
}

// ----------------------------------------------------------------------------------------------
// @desc Read the quarter's collected project records without creating the note or contacting a provider.
//   This is the low-latency path the calendar's "Suggested tasks" takes: everything it returns was resolved
//   by an earlier background pass, so a miss means the store has not filled in yet rather than an error.
// @param {object} app - Host-compatible Amplenote API.
// @param {object} scope - Resolved plan scope.
// @param {object} [options] - { includeInactive = false }: true also returns the records under Past projects, each
//   with isActive false, for a caller that must tell a retired project from one the store has never held.
// @returns {Promise<Array<QuarterProject>>} Stored projects, empty when the store does not exist yet.
export async function readCollectedProjectTasks(app, scope, { includeInactive = false } = {}) {
  const name = projectTaskStoreNoteName(scope);
  const found = checkedAppResult(await app.findNote({ name }));
  if (!found?.uuid) return [];
  const content = checkedAppResult(await app.getNoteContent({ uuid: found.uuid }));
  if (typeof content !== "string" || !content.trim()) return [];
  const { recordsByUuid, unreadableHeadings } = storedProjectRecords(content);
  if (unreadableHeadings.length) logIfEnabled("[project-task-store] unreadable sections", unreadableHeadings);
  const storedRecords = [...recordsByUuid.values()];
  if (includeInactive) return storedRecords;
  const activeRecords = storedRecords.filter(record => record.isActive);
  return activeRecords;
}

// ----------------------------------------------------------------------------------------------
// @desc Read every project record the store currently holds, keyed by project UUID, along with which root
//   each one sits beneath. A section whose payload cannot be parsed is reported rather than dropped, so a
//   corrupted project does not silently lose its accumulated task associations on the next write.
// @param {string} content - Full store note markdown.
// @returns {object} An object with the following properties:
//   - {Map<string, QuarterProject>} recordsByUuid - Stored project per project UUID, with isActive set from its root
//   - {Array<string>} unreadableHeadings - Heading texts whose payload could not be parsed
export function storedProjectRecords(content) {
  const headings = guideHeadingRanges(content);
  const recordsByUuid = new Map();
  const unreadableHeadings = [];
  for (const root of [ACTIVE_PROJECTS_HEADING, PAST_PROJECTS_HEADING]) {
    const rootHeading = headings.find(heading => heading.text === root);
    if (!rootHeading) continue;
    const projectHeadings = headings.filter(heading => heading.level === rootHeading.level + 1
      && heading.start >= rootHeading.bodyStart && heading.end <= rootHeading.end);
    for (const heading of projectHeadings) {
      const sectionBody = content.slice(heading.bodyStart, heading.end);
      const project = QuarterProject.fromStoreSection(sectionBody, { isActive: root === ACTIVE_PROJECTS_HEADING });
      if (!project) { unreadableHeadings.push(heading.text); continue; }
      recordsByUuid.set(project.uuid, project);
    }
  }
  return { recordsByUuid, unreadableHeadings };
}

// ----------------------------------------------------------------------------------------------
// @desc Write one project's section beneath the root its isActive calls for: "Active projects" or "Past projects".
//   A project new to the store is appended by rewriting only the root's last project section with the new section
//   after it, so adding a project never rewrites every other project: a root holding a quarter's projects can
//   outgrow the 100,000-character write limit long before any one section does. Only a root with no projects yet is
//   rewritten whole. A section already beneath the right root is replaced in place. A section beneath the other root
//   is moved, which needs a whole-note write, since a section write cannot remove a heading; when the note is too
//   large for one, the section is rewritten where it stands, and the move is left for a later write. Returns the
//   note content as it now stands so a caller advancing several projects in one pass does not have to re-read the
//   note between each write.
// @param {object} app - Host-compatible Amplenote API.
// @param {object} options - An object with the following properties:
//   - {string} content - Store note markdown as last read
//   - {object} noteHandle - Bare { uuid } handle for the store note
//   - {QuarterProject} project - Project to render; its isActive chooses the root
// @returns {Promise<string>} Updated store note markdown.
export async function writeProjectSection(app, { content, noteHandle, project }) {
  const headingText = projectSectionHeadingText(project);
  const body = project.toStoreSection();
  const rootText = project.isActive === false ? PAST_PROJECTS_HEADING : ACTIVE_PROJECTS_HEADING;
  const existing = guideSectionRange(content, headingText);
  if (existing && _sectionRootText(content, existing) !== rootText) {
    const movedContent = _contentWithSectionMoved(content, { body, existing, headingText, rootText });
    if (movedContent.length <= MAXIMUM_GUIDE_SECTION_CHARACTERS) {
      await replaceGuideSection(app, movedContent, noteHandle, null);
      logIfEnabled("[project-task-store] moved project section", { headingText, rootText });
      return movedContent;
    }
    logIfEnabled("[project-task-store] store too large to move project section", { headingText, rootText });
  }
  if (existing) {
    await replaceGuideSection(app, body, noteHandle, { heading: { level: existing.level, text: headingText } });
    return `${ content.slice(0, existing.bodyStart) }${ body }${ content.slice(existing.end) }`;
  }
  const root = guideSectionRange(content, rootText);
  if (!root) throw new Error(`Project task store is missing its "${ rootText }" heading`);
  const lastProject = _lastProjectSection(content, root);
  const target = lastProject || root;
  const targetBody = content.slice(target.bodyStart, target.end);
  const addition = `${ targetBody.endsWith("\n") || !targetBody ? "" : "\n" }## ${ headingText }\n\n${ body }`;
  await replaceGuideSection(app, `${ targetBody }${ addition }`, noteHandle,
    { heading: { level: target.level, text: target.text } });
  logIfEnabled("[project-task-store] added project section", { headingText });
  return `${ content.slice(0, target.bodyStart) }${ targetBody }${ addition }${ content.slice(target.end) }`;
}

