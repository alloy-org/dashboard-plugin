// ----------------------------------------------------------------------------------------------
// @desc Find the last project section beneath a root, which runs to the root's end.
// @param {string} content - Store note markdown.
// @param {object} root - The root's heading range from guideSectionRange.
// @returns {object|null} The last child heading range, or null when the root holds no project yet.
function _lastProjectSection(content, root) {
  const headings = guideHeadingRanges(content);
  const projectHeadings = headings.filter(heading => heading.level === root.level + 1 && heading.start >= root.bodyStart
    && heading.end <= root.end);
  return projectHeadings.length ? projectHeadings[projectHeadings.length - 1] : null;
}
