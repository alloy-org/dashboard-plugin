// ----------------------------------------------------------------------------------------------
// @desc Compose the note with one project's section taken from where it stands and appended to the end of the other
//   root, carrying the section's new body.
// @param {string} content - Store note markdown.
// @param {object} options - { body, existing, headingText, rootText }: existing is the section's current heading range,
//   rootText the root it moves beneath.
// @returns {string} Store note markdown after the move.
function _contentWithSectionMoved(content, { body, existing, headingText, rootText }) {
  const withoutSection = `${ content.slice(0, existing.start) }${ content.slice(existing.end) }`;
  const root = guideSectionRange(withoutSection, rootText);
  if (!root) throw new Error(`Project task store is missing its "${ rootText }" heading`);
  const rootBody = withoutSection.slice(root.bodyStart, root.end);
  const leadingBreak = rootBody.endsWith("\n") || !rootBody ? "" : "\n";
  const trailingBreak = root.end < withoutSection.length ? "\n" : "";
  const section = `${ leadingBreak }## ${ headingText }\n\n${ body.replace(/\n*$/, "\n") }${ trailingBreak }`;
  return `${ withoutSection.slice(0, root.end) }${ section }${ withoutSection.slice(root.end) }`;
}

// ----------------------------------------------------------------------------------------------
// @desc Find the last project section beneath a root, which runs to the root's end.
// @param {string} content - Store note markdown.
// @param {object} root - The root's heading range from guideSectionRange.
// @returns {object|null} The last child heading range, or null when the root holds no project yet.
function _lastProjectSection(content, root) {
  const headings = guideHeadingRanges(content);
  const projectHeadings = headings.filter(heading => heading.level === root.level + 1 && heading.start >= root.bodyStart
    && heading.end <= root.end);
  return projectHeadings.length ? projectHeadings[projectHeadings.length - 1] : null;
}

// ----------------------------------------------------------------------------------------------
// @desc Name the root a project section sits beneath.
// @param {string} content - Store note markdown.
// @param {object} section - The section's heading range.
// @returns {string|null} ACTIVE_PROJECTS_HEADING, PAST_PROJECTS_HEADING, or null when it sits beneath neither.
function _sectionRootText(content, section) {
  for (const rootText of [ACTIVE_PROJECTS_HEADING, PAST_PROJECTS_HEADING]) {
    const root = guideSectionRange(content, rootText);
    if (root && section.start >= root.bodyStart && section.end <= root.end) return rootText;
  }
  return null;
}
